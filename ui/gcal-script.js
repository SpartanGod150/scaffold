/* Google Apps Script for the two-way calendar bridge. The user pastes it into script.google.com and deploys it as a web app.
   The desktop app calls it; __SECRET__ is replaced with this setup's own key. */
window.GCAL_SCRIPT = [
"// Scaffold <-> Google Calendar bridge. Paste into script.google.com, add the service: Services (+) > Google Calendar API > Add,",
"// then Deploy > Web app (Execute as: Me, Access: Anyone).",
"const SECRET = '__SECRET__';",
"const V = 2;   // bridge version: all calendars, colors, descriptions, repeating events (needs the Google Calendar API service)",
"",
"function doPost(e) {",
"  const req = JSON.parse(e.postData.contents);",
"  if (req.secret !== SECRET) return out({ error: 'forbidden' });",
"  if (req.op === 'relay-post' || req.op === 'relay-poll') return relay(req);",
"  if (typeof Calendar === 'undefined') return out({ error: 'turn on the Google Calendar API in the script (Services +)' });",
"  const lock = LockService.getScriptLock();",
"  lock.waitLock(20000);",
"  try {",
"    if (req.op === 'pull') return out(pull(req));",
"    if (req.op === 'upsert') return out(upsert(req));",
"    if (req.op === 'delete') return out(del(req));",
"    return out({ error: 'unknown op' });",
"  } finally { lock.releaseLock(); }",
"}",
"",
"function iso(ms) { return new Date(ms).toISOString(); }",
"function md5(s) { return Utilities.base64Encode(Utilities.computeDigest(Utilities.DigestAlgorithm.MD5, s)); }",
"function gidOf(g) { return String(g || '').replace(/@google\\.com$/, ''); }   // ids from the old bridge",
"function calOf(req) { return req.cal || 'primary'; }",
"",
"function cals() {",
"  const items = [];",
"  let tok;",
"  do { const r = Calendar.CalendarList.list({ pageToken: tok, maxResults: 250 }); (r.items || []).forEach(function (c) { items.push(c); }); tok = r.nextPageToken; } while (tok);",
"  return items.map(function (c) {",
"    return { id: c.id, name: c.summaryOverride || c.summary, color: c.backgroundColor, primary: !!c.primary, ro: !(c.accessRole === 'owner' || c.accessRole === 'writer') };",
"  });",
"}",
"",
"// All calendars, -from..to. With since + sig: answers { same: true } when nothing changed (cheap check).",
"function pull(req) {",
"  const cs = cals(), sig = md5(JSON.stringify(cs));",
"  if (req.since && req.sig === sig) {",
"    let changed = false;",
"    for (let i = 0; i < cs.length && !changed; i++) {",
"      const r = Calendar.Events.list(cs[i].id, { updatedMin: iso(req.since - 120000), showDeleted: true, maxResults: 1, fields: 'items(id)' });",
"      changed = !!(r.items && r.items.length);",
"    }",
"    if (!changed) return { v: V, same: true, now: Date.now() };",
"  }",
"  const pal = {}, ec = Calendar.Colors.get().event;",
"  Object.keys(ec).forEach(function (k) { pal[k] = ec[k].background; });",
"  const events = [], rules = {};",
"  cs.forEach(function (c) {",
"    let tok;",
"    do {",
"      const r = Calendar.Events.list(c.id, { timeMin: iso(req.from), timeMax: iso(req.to), singleEvents: true, maxResults: 2500, pageToken: tok,",
"        fields: 'nextPageToken,items(id,status,summary,description,start,end,colorId,recurringEventId,originalStartTime,updated,extendedProperties)' });",
"      (r.items || []).forEach(function (ev) { if (ev.status !== 'cancelled') events.push(conv(ev, c)); });",
"      tok = r.nextPageToken;",
"    } while (tok);",
"    tok = null;",
"    do {   // the repeat rule of each series",
"      const r = Calendar.Events.list(c.id, { timeMin: iso(req.from), timeMax: iso(req.to), singleEvents: false, maxResults: 2500, pageToken: tok, fields: 'nextPageToken,items(id,recurrence)' });",
"      (r.items || []).forEach(function (ev) { if (ev.recurrence) rules[ev.id] = ev.recurrence.join('\\n'); });",
"      tok = r.nextPageToken;",
"    } while (tok);",
"  });",
"  return { v: V, events: events, cals: cs, colors: pal, rules: rules, sig: sig, now: Date.now() };",
"}",
"",
"function conv(ev, c) {",
"  const allDay = !!ev.start.date, pr = (ev.extendedProperties && ev.extendedProperties.private) || {}, os = ev.originalStartTime;",
"  return { gid: ev.id, cal: c.id, title: ev.summary || '(no title)', desc: ev.description || '', allDay: allDay,",
"    sd: allDay ? ev.start.date : '', ed: allDay ? ev.end.date : '',",
"    start: Date.parse(allDay ? ev.start.date + 'T00:00:00' : ev.start.dateTime), end: Date.parse(allDay ? ev.end.date + 'T00:00:00' : ev.end.dateTime),",
"    rec: !!ev.recurringEventId, series: ev.recurringEventId || '', ostart: os ? (os.date || Date.parse(os.dateTime)) : '',",
"    color: ev.colorId || '', upd: Date.parse(ev.updated), sid: pr.scaffoldId || '' };",
"}",
"",
"function body(req) {",
"  const b = { summary: req.title, colorId: req.color || null };",
"  if (req.desc != null) b.description = req.desc;",
"  if (req.allDay) { b.start = { date: req.sd, dateTime: null }; b.end = { date: req.ed, dateTime: null }; }",
"  else { b.start = { dateTime: iso(req.start), date: null, timeZone: req.tz || null }; b.end = { dateTime: iso(req.end), date: null, timeZone: req.tz || null }; }",
"  return b;",
"}",
"function findBySid(cal, sid) {",
"  const r = Calendar.Events.list(cal, { privateExtendedProperty: 'scaffoldId=' + sid, maxResults: 5, singleEvents: false });",
"  return r.items && r.items.length ? r.items[0] : null;",
"}",
"function ruleLine(rec) { return (rec || []).filter(function (l) { return /^RRULE:/.test(l); })[0] || ''; }",
"function others(rec) { return (rec || []).filter(function (l) { return !/^RRULE:/.test(l); }); }",
"// The series stops right before the occurrence that started at ostart.",
"function untilBefore(rule, ostart, allDay) {",
"  let until;",
"  if (allDay) { const d = new Date(String(ostart) + 'T12:00:00Z'); d.setUTCDate(d.getUTCDate() - 1); until = Utilities.formatDate(d, 'UTC', 'yyyyMMdd'); }",
"  else until = Utilities.formatDate(new Date(+ostart - 1000), 'UTC', \"yyyyMMdd'T'HHmmss'Z'\");",
"  return rule.replace(/;(COUNT|UNTIL)=[^;]*/g, '') + ';UNTIL=' + until;",
"}",
"",
"// req: cal, oldCal, gid, sid, title, desc, color, allDay, sd, ed, start, end, tz, rrule ('' = none), keepRule, scope ('one'|'following'|'all'), series, ostart",
"function upsert(req) {",
"  const cal = calOf(req), b = body(req);",
"  let gid = gidOf(req.gid);",
"  if (req.series && req.scope && req.scope !== 'one') {",
"    const series = gidOf(req.series), oldCal = req.oldCal || cal, m = Calendar.Events.get(oldCal, series);",
"    const osMs = req.allDay ? Date.parse(req.ostart + 'T00:00:00') : +req.ostart;",
"    const mStart = m.start.date ? Date.parse(m.start.date + 'T00:00:00') : Date.parse(m.start.dateTime);",
"    const first = Math.abs(osMs - mStart) < 60000;",
"    if (req.scope === 'all' || first) {",
"      if (!req.allDay) {   // same shift for the whole series",
"        const s = mStart + (req.start - osMs);",
"        b.start.dateTime = iso(s); b.end.dateTime = iso(s + (req.end - req.start));",
"      } else if (m.start.date) {",
"        const shift = Math.round((Date.parse(req.sd + 'T00:00:00') - osMs) / 86400000), d0 = new Date(m.start.date + 'T12:00:00Z');",
"        d0.setUTCDate(d0.getUTCDate() + shift);",
"        const len = Math.round((Date.parse(req.ed + 'T00:00:00') - Date.parse(req.sd + 'T00:00:00')) / 86400000), d1 = new Date(d0.getTime());",
"        d1.setUTCDate(d1.getUTCDate() + len);",
"        b.start.date = Utilities.formatDate(d0, 'UTC', 'yyyy-MM-dd'); b.end.date = Utilities.formatDate(d1, 'UTC', 'yyyy-MM-dd');",
"      }",
"      b.recurrence = req.keepRule || !req.rrule ? m.recurrence : others(m.recurrence).concat([req.rrule]);",
"      if (oldCal !== cal) Calendar.Events.move(oldCal, series, cal);",
"      const r = Calendar.Events.patch(b, cal, series);",
"      return { gid: r.id, upd: Date.parse(r.updated) };",
"    }",
"    // \"This and following\": end the old series before this occurrence, start a new one here.",
"    let rule = req.keepRule || !req.rrule ? ruleLine(m.recurrence) : req.rrule;",
"    const cm = /;COUNT=(\\d+)/.exec(ruleLine(m.recurrence));",
"    if (cm && (req.keepRule || !req.rrule)) {",
"      const before = (Calendar.Events.instances(oldCal, series, { timeMax: iso(osMs), maxResults: 2500 }).items || []).length;",
"      rule = rule.replace(/;COUNT=\\d+/, ';COUNT=' + Math.max(1, +cm[1] - before));",
"    }",
"    Calendar.Events.patch({ recurrence: others(m.recurrence).concat([untilBefore(ruleLine(m.recurrence), req.ostart, !!m.start.date)]) }, oldCal, series);",
"    b.recurrence = [rule];",
"    if (req.sid) b.extendedProperties = { private: { scaffoldId: req.sid } };",
"    const r = Calendar.Events.insert(b, cal);",
"    return { gid: r.id, upd: Date.parse(r.updated) };",
"  }",
"  if (!gid && req.sid) { const f = findBySid(cal, req.sid); if (f) gid = f.id; }",
"  if (!gid) {",
"    b.extendedProperties = { private: { scaffoldId: req.sid || '' } };",
"    if (req.rrule) b.recurrence = [req.rrule];",
"    const r = Calendar.Events.insert(b, cal);",
"    return { gid: r.id, upd: Date.parse(r.updated) };",
"  }",
"  if (req.oldCal && req.oldCal !== cal && !req.series) Calendar.Events.move(req.oldCal, gid, cal);",
"  if (req.rrule && !req.series) b.recurrence = [req.rrule];",
"  const r = Calendar.Events.patch(b, cal, gid);",
"  return { gid: r.id, upd: Date.parse(r.updated) };",
"}",
"",
"// req: cal, gid, scope, series, ostart, allDay",
"function del(req) {",
"  const cal = calOf(req);",
"  try {",
"    if (req.series && req.scope === 'all') Calendar.Events.remove(cal, gidOf(req.series));",
"    else if (req.series && req.scope === 'following') {",
"      const m = Calendar.Events.get(cal, gidOf(req.series)), mStart = m.start.date ? m.start.date : Date.parse(m.start.dateTime);",
"      if (String(mStart) === String(req.ostart) || Math.abs(+mStart - +req.ostart) < 60000) Calendar.Events.remove(cal, gidOf(req.series));",
"      else Calendar.Events.patch({ recurrence: others(m.recurrence).concat([untilBefore(ruleLine(m.recurrence), req.ostart, !!m.start.date)]) }, cal, gidOf(req.series));",
"    } else Calendar.Events.remove(cal, gidOf(req.gid));",
"  } catch (x) { if (!/410|404|deleted|Not Found/i.test(String(x))) throw x; }",
"  return { ok: true };",
"}",
"",
"",
"// Backup mailbox for Scaffold's sync, used when a network blocks the normal one. Holds encrypted messages for 6 hours.",
"function relay(req) {",
"  const cache = CacheService.getScriptCache(), lock = LockService.getUserLock();",
"  lock.waitLock(20000);",
"  try {",
"    let seq = +(cache.get('seq') || 0);",
"    const now = Date.now(), ls = JSON.parse(cache.get('ls') || '{}');",
"    if (req.op === 'relay-post') {",
"      const put = {};",
"      (req.msgs || []).forEach(function (m) { if (typeof m === 'string' && m.length < 90000) put['m' + (++seq)] = m; });",
"      put.seq = String(seq);",
"      cache.putAll(put, 21600);",
"      return out({ seq: seq });",
"    }",
"    if (req.listen && req.from) { ls[req.from] = now; }",
"    Object.keys(ls).forEach(function (k) { if (ls[k] < now - 180000) delete ls[k]; });",
"    cache.put('ls', JSON.stringify(ls), 21600);",
"    const since = Math.max(+req.since || 0, seq - 200), keys = [];",
"    for (let i = since + 1; i <= seq; i++) keys.push('m' + i);",
"    const got = keys.length ? cache.getAll(keys) : {}, msgs = [];",
"    keys.forEach(function (k) { if (got[k]) msgs.push(got[k]); });",
"    const others = Object.keys(ls).filter(function (k) { return k !== req.from && ls[k] > now - 120000; }).length;",
"    return out({ seq: seq, msgs: msgs, listeners: others });",
"  } finally { lock.releaseLock(); }",
"}",
"",
"function out(o) { return ContentService.createTextOutput(JSON.stringify(o)).setMimeType(ContentService.MimeType.JSON); }",
""].join('\n');

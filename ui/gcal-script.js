/* Google Apps Script for the two-way calendar bridge. The user pastes it into script.google.com and deploys it as a web app.
   The desktop app calls it; __SECRET__ is replaced with this setup's own key. */
window.GCAL_SCRIPT = [
"// Scaffold <-> Google Calendar bridge. Paste into script.google.com, then Deploy > Web app (Execute as: Me, Access: Anyone).",
"const SECRET = '__SECRET__';",
"",
"function doPost(e) {",
"  const req = JSON.parse(e.postData.contents);",
"  if (req.secret !== SECRET) return out({ error: 'forbidden' });",
"  const lock = LockService.getScriptLock();",
"  lock.waitLock(20000);",
"  try {",
"    const cal = CalendarApp.getDefaultCalendar();",
"    if (req.op === 'pull') {",
"      const events = cal.getEvents(new Date(req.from), new Date(req.to)).map(function (ev) {",
"        return { gid: ev.getId(), title: ev.getTitle(), start: ev.getStartTime().getTime(), end: ev.getEndTime().getTime(),",
"          allDay: ev.isAllDayEvent(), rec: ev.isRecurringEvent(), upd: ev.getLastUpdated().getTime(), sid: ev.getTag('scaffoldId') || '' };",
"      });",
"      return out({ events: events, now: Date.now() });",
"    }",
"    if (req.op === 'upsert') {",
"      let ev = null;",
"      if (req.gid) { try { ev = cal.getEventById(req.gid); } catch (x) { ev = null; } }",
"      if (!ev && req.sid) ev = findBySid(cal, req.sid);",
"      if (!ev) {",
"        ev = req.allDay ? cal.createAllDayEvent(req.title, new Date(req.start)) : cal.createEvent(req.title, new Date(req.start), new Date(req.end));",
"        ev.setTag('scaffoldId', req.sid);",
"      } else {",
"        ev.setTitle(req.title);",
"        if (req.allDay) ev.setAllDayDate(new Date(req.start)); else ev.setTime(new Date(req.start), new Date(req.end));",
"      }",
"      return out({ gid: ev.getId(), upd: ev.getLastUpdated().getTime() });",
"    }",
"    if (req.op === 'delete') {",
"      try { const ev = cal.getEventById(req.gid); if (ev) ev.deleteEvent(); } catch (x) {}",
"      return out({ ok: true });",
"    }",
"    return out({ error: 'unknown op' });",
"  } finally { lock.releaseLock(); }",
"}",
"",
"function findBySid(cal, sid) {",
"  const day = 86400000, now = Date.now();",
"  const list = cal.getEvents(new Date(now - 60 * day), new Date(now + 400 * day));",
"  for (let i = 0; i < list.length; i++) if (list[i].getTag('scaffoldId') === sid) return list[i];",
"  return null;",
"}",
"",
"function out(o) { return ContentService.createTextOutput(JSON.stringify(o)).setMimeType(ContentService.MimeType.JSON); }",
""].join('\n');
